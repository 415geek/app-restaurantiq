/**
 * Every literal string the /print report renders, in the three report
 * languages. `REPORT_STRINGS[lang]` is one typed dictionary: English is the
 * source of truth for the shape, Chinese and Spanish must provide every key.
 *
 * Templates use `{name}` placeholders filled by `fill()`. Nothing here formats
 * numbers — formatters live in format.ts and stay locale-neutral (US number
 * formats and USD everywhere).
 */
