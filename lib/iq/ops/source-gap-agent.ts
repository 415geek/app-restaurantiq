/**
 * Source-gap agent — keeps paid reports from staying "partial" forever.
 *
 * Weekly (app/api/iq/ops?task=source_gaps, Monday 12:00 UTC) it:
 *   a) SCANS paid reports from the last 60 days and counts, per data source
 *      D1..D12, how many carry a `sources[]` row with status partial / failed;
 *   b) FILLS gaps the in-house loaders can fix — D3 (iq_lodes_wac), D5 (iq_poi),
 *      D7 (iq_poi_snapshot): when the table is now loaded, the oldest affected
 *      reports are regenerated (≤ maxReports, cost-capped by the 360° pipeline)
 *      and the new model is committed ONLY when more sources are `ok` than
 *      before and the report does not drop from tier `paid` to `precheck`;
 *   c) DISCOVERS external alternatives for the gaps no loader can fix (D4
 *      isochrones, D7 foot traffic, D8 rent comps, D9 transit ridership, D11
 *      pipeline, Chinese-community signals) with ≤ maxSearches web searches,
 *      scores every hit heuristically (gov / edu / open-data hosts, license
 *      words) and inserts unseen URLs into `iq_source_candidates` as `new` —
 *      never adopted automatically;
 *   d) PERSISTS one `iq_source_gap_runs` row.
 *
 * Never throws; honours `budgetMs`; `dryRun` reads and searches but writes
 * nothing. Every side effect goes through `deps` so the whole flow is
 * unit-tested without network or DB.
 */
import type { WebSearchHit, WebSearchOutcome } from '@/lib/iq/data/rent-comps';
import type { DataSourceId } from '@/lib/iq/data/types';
import type { SourceRow } from '@/lib/iq/model/schema';
import { createBudget, prefixedLog, round4, type OpsBaseOptions, type OpsLog } from './common';

export const ALL_SOURCE_IDS: readonly DataSourceId[] = ['D1', 'D2', 'D3', 'D4', 'D5', 'D6', 'D7', 'D8', 'D9', 'D10', 'D11', 'D12'];

/** Reports younger than this are scanned. */
export const SCAN_WINDOW_DAYS = 60;
/** A report regenerated by this agent is left alone for this long (avoids loops on gaps that never improve). */
export const REGEN_COOLDOWN_DAYS = 30;
/** A regeneration is only started with at least this much budget left (one 360° run ≈ 30–90 s). */
export const REGEN_MIN_REMAINING_MS = 60_000;
/** A web search is only started with at least this much budget left. */
export const SEARCH_MIN_REMAINING_MS = 20_000;
export const DEFAULT_MAX_REPORTS = 3;
export const DEFAULT_MAX_SEARCHES = 3;
/** Hits below this heuristic score are dropped before dedupe / insert. */
export const MIN_CANDIDATE_SCORE = 0.25;
export const MAX_CANDIDATES_PER_SEARCH = 5;
const MAX_REPORTS_SCANNED = 500;

