/**
 * Regenerates lib/funnel/iq-cjk-vocabulary.json — the set of Chinese characters
 * this product actually writes (评审 Spec v2 §4.6 「全链路 UTF-8 校验」).
 *
 * The report LLMs write about our domain in our vocabulary, so a Han character
 * that appears in generated prose but nowhere in our own prompts, templates and
 * UI copy is a strong signal of corruption ("礏盒装" for 「礼盒装」). Data-borne
 * names (addresses, competitors) are allowed separately at scan time by passing
 * the report's own context as extra vocabulary — never by widening this file.
 *
 * Usage: node scripts/build-cjk-vocabulary.mjs   (then commit the JSON)
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, extname } from 'node:path';

const ROOT = process.cwd();
const DIRS = ['lib', 'components', 'app', 'docs', 'qa/fixtures'];
const EXT = new Set(['.ts', '.tsx', '.json', '.yaml', '.yml', '.md', '.css']);
const SKIP = new Set(['node_modules', '.next', '.git', 'out']);
const HAN = /\p{Script=Han}/u;

/** Characters that are correct but too rare to appear in our own corpus. */
const EXTRA = '囍佬';

function walk(dir, files = []) {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return files;
  }
  for (const name of entries) {
    if (SKIP.has(name)) continue;
    const p = join(dir, name);
    let st;
    try {
      st = statSync(p);
    } catch {
      continue;
    }
    if (st.isDirectory()) walk(p, files);
    else if (EXT.has(extname(name))) files.push(p);
  }
  return files;
}

const chars = new Set();
let scanned = 0;
for (const dir of DIRS) {
  for (const file of walk(join(ROOT, dir))) {
    let text;
    try {
      text = readFileSync(file, 'utf8');
    } catch {
      continue;
    }
    scanned++;
    for (const ch of text) if (HAN.test(ch)) chars.add(ch);
  }
}
for (const ch of EXTRA) chars.add(ch);

const sorted = [...chars].sort((a, b) => a.codePointAt(0) - b.codePointAt(0));
const out = {
  _comment: 'Generated by scripts/build-cjk-vocabulary.mjs — Han characters this product writes. Do not hand-edit.',
  generated_from_files: scanned,
  count: sorted.length,
  chars: sorted.join(''),
};
writeFileSync(join(ROOT, 'lib', 'funnel', 'iq-cjk-vocabulary.json'), `${JSON.stringify(out, null, 2)}\n`, 'utf8');
console.log(`[cjk-vocabulary] ${sorted.length} characters from ${scanned} files`);
